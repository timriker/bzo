// Turns upstream's `globalDBItems` table into `server/bzdb-defaults.cjs` --
// the world variables every bzfs starts with, which is the only way to tell
// a server's *deliberate* `-set` from the value it would have had anyway.
// A remote import writes the difference into the map it exports (see
// `collectNonDefaultVariables` in server/remote-world-import.cjs).
//
// Kept as generated source rather than read at runtime: bzo does not depend
// on a BZFlag checkout being present, and the table changes about once a
// release. Regenerate against a newer upstream with:
//
//   node scripts/gen-bzdb-defaults.mjs ~/bzflag > server/bzdb-defaults.cjs

import fs from 'node:fs';
import path from 'node:path';

const root = process.argv[2] || path.join(process.env.HOME || '', 'bzflag');
const source = path.join(root, 'src', 'common', 'global.cxx');
let text;
try {
  text = fs.readFileSync(source, 'utf8');
} catch {
  console.error(`No upstream global.cxx at ${source}. Pass the BZFlag checkout as the first argument.`);
  process.exit(1);
}

const table = text.match(/globalDBItems\[\]\s*=\s*\{([\s\S]*?)\n\};/);
if (!table) {
  console.error(`Could not find globalDBItems in ${source}.`);
  process.exit(1);
}

const entries = [];
for (const line of table[1].split('\n')) {
  const match = line.match(/^\s*\{\s*"([^"]*)"\s*,\s*"([^"]*)"\s*,/);
  if (match) entries.push([match[1], match[2]]);
}
if (entries.length === 0) {
  console.error('globalDBItems parsed to nothing; the table\'s shape must have changed.');
  process.exit(1);
}

const width = Math.max(...entries.map(([name]) => name.length));
const lines = [
  '/*',
  ' * Copyright (C) 2025-2026 Tim Riker <timriker@gmail.com>',
  ' * Licensed under the GNU Affero General Public License v3.0 (AGPLv3).',
  ' * Source: https://github.com/timriker/bzo',
  ' * See LICENSE or https://www.gnu.org/licenses/agpl-3.0.html',
  ' */',
  '',
  '// Generated by scripts/gen-bzdb-defaults.mjs -- do not edit by hand.',
  '//',
  `// Upstream's own world-variable defaults (${entries.length} of them), from`,
  '// `globalDBItems` in `src/common/global.cxx`. A bzfs sends its whole BZDB',
  '// to a player who enters, with no indication of which values the operator',
  '// or the map actually changed, so this table is what tells the two apart.',
  '',
  'const BZDB_DEFAULTS = Object.freeze({',
  ...entries.map(([name, value]) => `  ${JSON.stringify(name).padEnd(width + 3)}: ${JSON.stringify(value)},`),
  '});',
  '',
  'module.exports = { BZDB_DEFAULTS };',
  '',
];
process.stdout.write(lines.join('\n'));
