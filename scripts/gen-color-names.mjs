// Turns upstream's colour-name table (`colorSets` in
// `src/common/ParseColor.cxx`, generated there from X11's rgb.txt) into
// `public/js/color-names.mjs` (mirrored to `server/color-names.cjs`), so a map's `color red` or `-set _skyColor grey3`
// names the colour upstream would. Kept as generated source for the same
// reason `server/bzdb-defaults.cjs` is: bzo does not depend on a BZFlag
// checkout. Regenerate with:
//
//   node scripts/gen-color-names.mjs ~/bzflag > public/js/color-names.mjs
//   node scripts/mirror-pair.mjs color-names

import fs from 'node:fs';
import path from 'node:path';

const root = process.argv[2] || path.join(process.env.HOME || '', 'bzflag');
const source = fs.readFileSync(path.join(root, 'src', 'common', 'ParseColor.cxx'), 'utf8');
const entries = [...source.matchAll(/\{\s*"([^"]+)",\s*\{\s*([\d.]+)f,\s*([\d.]+)f,\s*([\d.]+)f\s*\}\s*\}/g)]
  .map(([, name, r, g, b]) => [name, [Number(r), Number(g), Number(b)]]);
if (entries.length < 700) throw new Error(`only ${entries.length} colours found`);

const lines = entries.map(([name, rgb]) => `  [${JSON.stringify(name)}, [${rgb.join(', ')}]],`);
process.stdout.write(`/*
 * Copyright (C) 2025-2026 Tim Riker <timriker@gmail.com>
 * Licensed under the GNU Affero General Public License v3.0 (AGPLv3).
 * Source: https://github.com/timriker/bzo
 * See LICENSE or https://www.gnu.org/licenses/agpl-3.0.html
 */

// Generated by scripts/gen-color-names.mjs -- do not edit by hand.
//
// Upstream's colour names (${entries.length} of them), in its own order, from
// \`colorSets\` in \`src/common/ParseColor.cxx\`. Order matters: upstream takes
// the first name a string starts with.

export const COLOR_NAMES = Object.freeze([
${lines.join('\n')}
]);
`);
